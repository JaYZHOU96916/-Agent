export function localizeSystemMessage(message: string, language: Language): string {
  if (language === "zh") return message;
  const modelStatus = message.match(/^模型服务返回 HTTP (\d+)；请检查模型、密钥及配额。$/);
  if (modelStatus) return `Model service returned HTTP ${modelStatus[1]}. Check the model, API key, and quota.`;
  return serverMessagesEn[message] ?? message;
}
